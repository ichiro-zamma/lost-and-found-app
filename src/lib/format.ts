// 日時表示の共通化
// 落とし物・拾得物など、日時を表示するときに共通して使う関数
export function formatDateTime(date: Date): string {
   // Date型の日時を受け取り、文字列(string)として返す関数
   // export：他のファイルからimportして使えるようにする

   //Intl.DateTimeFormat＝地域に合わせた日時の表示形式を作る機能
   //指定したフォーマットで、日時を「月・日・時・分」のパーツ群に切り分ける
  const parts = new Intl.DateTimeFormat('ja-JP', {
    timeZone: 'Asia/Tokyo', // 日本時間で表示する
    // 「日本時間(JST)で表示する」と指定
    // DBの日時がUTCでも、日本時間に変換して表示してくれる

    /* --- 切り分ける際のフォーマット（形式）ルール指定 --- */
    /* ※ここでは取り出す処理ではなく「どんな形の部品を作るか」の設定をしています */

    month: 'numeric',
    // 月を「9」のような数字だけの部品にする指定（「09」や「9月」にしない）
    // 後から自分の手で「月」をつけるため、あらかじめ単位（月）を外した純粋な数字にする

    day: 'numeric',
    // 日を「13」のような数字だけの部品にする指定（「13日」にしない）
    // 後から「日」を後付けできるように余計な文字を含めない

    hour: 'numeric',
    // 時を「18」のような数字だけの部品にする指定（「18時」にしない）
    // 後から「時」を後付けできるように余計な文字を含めない

    minute: '2-digit',
    // 分を必ず2桁の数字部品（例: 5分なら「05」）にする指定
    // 「05分」ではなく「05」という2桁の数字だけを揃える

    hour12: false,
    // 時間を12時間制（午前/午後）ではなく、24時間制（0〜23）の数字部品にする設定
    // true  → 「午前」「午後」という別パーツが増え、数字も 1〜12 になる
    // false → 「18」のように24時間表記のシンプルな数字だけになる
  }).formatToParts(date)
  // 指定した形式でdateを日本時間に変換する
  // formatToParts()を使うことで、
  // 「月」「日」「時」「分」をそれぞれ別々に取り出せる
  //「日時をそのまま文字列にするのではなく、
  // { type: 'month', value: '9' } のようなラベル付きの部品データに切り分ける処理」
  

  //普通の .format(date) を使った場合
  // 結果は1つのつながった「完成品の文字列」になる"9/13 18:50"
  //これだと、「9」だけ、「18」だけを後から取り出すのが大変です（文字をカットしたり探したりする必要がある）

//   .formatToParts(date) を使った場合
// 文字列としてつなげず、「月」「日」「時」「分」を一つひとつのパーツにバラバラにして返してくれます。
//オリジナルの表示を簡単に組み立てられます。


  const month = parts.find((part) => part.type === 'month')?.value
  // partsの中から「月」の部分を探して、その値を取得
  // 例："9"
  const day = parts.find((part) => part.type === 'day')?.value
  // partsの中から「日」の部分を探して、その値を取得
  // 例："13"
  const hour = parts.find((part) => part.type === 'hour')?.value
  // partsの中から「時」の部分を探して、その値を取得
  // 例："18"
  // UTCの9時ではなく、日本時間の18時になる
  const minute = parts.find((part) => part.type === 'minute')?.value
  // partsの中から「分」の部分を探して、その値を取得
  // 例："50"

  return `${month}月${day}日 ${hour}時${minute}分`
  // 取得した「月・日・時・分」を1つの文字列にする
  // 例：「9月13日 18時50分」
}
// DB(PostgreSQL)は、TIMESTAMP型の日時を**UTC(協定世界時)**として保存する、というのが一般的な設計
// 画面に表示する時だけ、利用者の地域の時刻(今回なら日本時間、UTC+9)に変換する
// 「保存」と「表示」の基準を分けることで、将来どの地域で使っても、時刻の基準がブレない、というのがメリット

//DBでは日時をUTC(協定世界時)で保存し、画面表示時に日本時間(JST)へ変換する設計にしています。
// これは、特定の地域のタイムゾーンに依存せず、時刻の基準を一意に保つための一般的な設計方針です。
// 将来的に海外展開する場合にも、この設計であれば対応しやすくなります。

// 「時刻の基準を一意に固定できる」

// 「Intl が勝手につける単位」と「自分がつけたい単位」がズレてしまうから
// 例えば、Intl が自動で単位をつけるとこんな形になります：
// "2026年9月13日 18:50" // 「年」まで入ったり、「時・分」が「:」になったりする

// なぜ一度「数字だけ」にするのか？
// Intl は「年を入れるか」「時分をコロンにするか」を勝手に判断してしまうので、プログラマーは一番確実な方法をとります。

// Intl に頼むこと： 「余計な漢字や記号（年やコロン）は付けず、純粋な数字だけに切り分けて！」（これが numeric です）

// 月："9"

// 日："13"

// 時："18"

// 分："50"

// 自分でやること： 「よし、綺麗な数字だけ揃ったから、自分の手で『月・日・時・分』をガッチャンコしよう！」

// ${month}月${day}日 ${hour}時${minute}分

// → "9月13日 18時50分"

// まとめ
// 単位を消す（数字だけにする）理由：
// Intl が勝手に余計な文字（「年」や「:」など）を混ぜてくるのを防ぎ、自分が完全にコントロールできる「ピュアな数字」にするため。
//「最初から理想の漢字つきで取り出す」という指定が Intl には存在しないため、【一度数字だけにする ➔ 自分で理想の漢字をつける】　